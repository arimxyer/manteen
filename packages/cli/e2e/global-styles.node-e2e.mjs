/** Managed package styles through the built CLI under real Node. */
import { strict as assert } from "node:assert";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { after, test } from "node:test";
import { pathToFileURL } from "node:url";

import { childEnv } from "./helpers/child-env.mjs";

const PKG_ROOT = resolve(import.meta.dirname, "..");
const CLI = join(PKG_ROOT, "dist", "cli.mjs");
const WORK = mkdtempSync(join(tmpdir(), "manteen-global-styles-"));
const REGISTRY = join(WORK, "registry");
const PROJECT = join(WORK, "project");
const STYLES = join(PROJECT, "src", "manteen.css");
const RECEIPT = join(PROJECT, "manteen.lock.json");
const SCAFFOLD =
  "/* Generated by manteen. Put project overrides in the host stylesheet imported after this file. */\n";

assert.equal(process.versions.bun, undefined, "the e2e tier must run under node");
assert.ok(existsSync(CLI), `${CLI} is missing; build the CLI first`);

after(() => rmSync(WORK, { recursive: true, force: true }));

mkdirSync(REGISTRY, { recursive: true });
mkdirSync(join(PROJECT, "src"), { recursive: true });
mkdirSync(join(PROJECT, "node_modules", "@mantine", "carousel"), { recursive: true });

writeFileSync(
  join(REGISTRY, "styled.json"),
  `${JSON.stringify(
    {
      $schema: "https://ui.shadcn.com/schema/registry-item.json",
      name: "styled",
      type: "registry:ui",
      dependencies: ["@mantine/carousel@^9"],
      files: [],
      css: { '@import "@mantine/carousel/styles.css"': {} },
    },
    null,
    2,
  )}\n`,
);
writeFileSync(
  join(PROJECT, "package.json"),
  `${JSON.stringify(
    {
      name: "global-styles-consumer",
      private: true,
      packageManager: "npm@10.9.2",
      dependencies: { "@mantine/carousel": "^9.0.0" },
    },
    null,
    2,
  )}\n`,
);
writeFileSync(
  join(PROJECT, "node_modules", "@mantine", "carousel", "package.json"),
  `${JSON.stringify({ name: "@mantine/carousel", version: "9.0.0" }, null, 2)}\n`,
);
writeFileSync(
  join(PROJECT, "tsconfig.json"),
  `${JSON.stringify(
    {
      compilerOptions: {
        baseUrl: ".",
        paths: {
          "@/components/*": ["./src/components/*"],
          "@/components/ui/*": ["./src/components/ui/*"],
          "@/hooks/*": ["./src/hooks/*"],
          "@/lib/*": ["./src/lib/*"],
        },
      },
    },
    null,
    2,
  )}\n`,
);
writeFileSync(
  join(PROJECT, "manteen.json"),
  `${JSON.stringify(
    {
      registries: { "@test": `${pathToFileURL(REGISTRY).href}/{name}.json` },
      aliases: {
        components: "@/components",
        ui: "@/components/ui",
        hooks: "@/hooks",
        lib: "@/lib",
      },
      styles: "src/manteen.css",
      tsconfig: "tsconfig.json",
    },
    null,
    2,
  )}\n`,
);
writeFileSync(STYLES, SCAFFOLD);
writeFileSync(
  RECEIPT,
  `${JSON.stringify({ lockfileVersion: 1, items: [], theme: null }, null, 2)}\n`,
);

function run(args) {
  return spawnSync(process.execPath, [CLI, ...args, "--cwd", PROJECT], {
    encoding: "utf8",
    env: childEnv(),
  });
}

test("v1 stays byte-identical on read and a successful add writes v2 styles", () => {
  const before = readFileSync(RECEIPT, "utf8");
  const diff = run(["diff"]);
  assert.equal(diff.status, 0, diff.stderr);
  assert.equal(readFileSync(RECEIPT, "utf8"), before);

  const add = run(["add", "@test/styled", "--yes"]);
  assert.equal(add.status, 0, add.stderr);
  assert.equal(
    readFileSync(STYLES, "utf8"),
    `${SCAFFOLD}@import "@mantine/carousel/styles.css";\n`,
  );

  const receipt = JSON.parse(readFileSync(RECEIPT, "utf8"));
  assert.equal(receipt.lockfileVersion, 2);
  assert.equal(receipt.styles.destination, "src/manteen.css");
  assert.deepEqual(receipt.styles.sources, [
    {
      itemId: "@test/styled",
      dependsOn: [],
      imports: ["@mantine/carousel/styles.css"],
    },
  ]);
});

test("repeat install is clean and owned drift refuses until forced", () => {
  const receiptBefore = readFileSync(RECEIPT, "utf8");
  const repeat = run(["add", "@test/styled", "--yes"]);
  assert.equal(repeat.status, 0, repeat.stderr);
  assert.match(repeat.stdout, /unchanged\s+src\/manteen\.css/);
  assert.equal(readFileSync(RECEIPT, "utf8"), receiptBefore);

  writeFileSync(STYLES, `${readFileSync(STYLES, "utf8")}body {}\n`);
  const refused = run(["add", "@test/styled", "--yes"]);
  assert.equal(refused.status, 1);
  assert.match(refused.stderr, /global-styles-drift/);
  assert.match(readFileSync(STYLES, "utf8"), /body \{\}/);

  const diff = run(["diff"]);
  assert.equal(diff.status, 0, diff.stderr);
  assert.match(diff.stdout, /styles\n\s+local-only/);

  const forced = run(["add", "@test/styled", "--yes", "--force"]);
  assert.equal(forced.status, 0, forced.stderr);
  assert.match(forced.stderr, /warn\s+global-styles-drift/);
  assert.equal(
    readFileSync(STYLES, "utf8"),
    `${SCAFFOLD}@import "@mantine/carousel/styles.css";\n`,
  );
});
