/** Real compiled Carousel and Dropzone items through the built CLI under Node. */
import { strict as assert } from "node:assert";
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { after, test } from "node:test";
import { pathToFileURL } from "node:url";

import { childEnv } from "./helpers/child-env.mjs";

const REPO_ROOT = resolve(import.meta.dirname, "../../..");
const CLI = join(REPO_ROOT, "packages", "cli", "dist", "cli.mjs");
const REGISTRY = join(REPO_ROOT, "public", "r");
const WORK = mkdtempSync(join(tmpdir(), "manteen-extension-content-"));
const PROJECT = join(WORK, "project");
const STYLES = join(PROJECT, "src", "manteen.css");
const SCAFFOLD =
  "/* Generated by manteen. Put project overrides in the host stylesheet imported after this file. */\n";

assert.equal(process.versions.bun, undefined, "the e2e tier must run under node");
assert.ok(existsSync(CLI), `${CLI} is missing; build the CLI first`);
assert.ok(existsSync(join(REGISTRY, "cards-carousel.json")), "build the house registry first");
assert.ok(existsSync(join(REGISTRY, "dropzone-button.json")), "build the house registry first");

after(() => rmSync(WORK, { recursive: true, force: true }));

mkdirSync(join(PROJECT, "src"), { recursive: true });

const dependencies = {
  "@mantine/carousel": "^9.5.0",
  "@mantine/core": "^9.5.0",
  "@mantine/dropzone": "^9.5.0",
  "@mantine/hooks": "^9.5.0",
  "@tabler/icons-react": "^3.45.0",
};

writeFileSync(
  join(PROJECT, "package.json"),
  `${JSON.stringify(
    {
      name: "extension-content-consumer",
      private: true,
      packageManager: "npm@10.9.2",
      dependencies,
    },
    null,
    2,
  )}\n`,
);

for (const [name, range] of Object.entries(dependencies)) {
  const version = range.replace(/^\^/, "");
  const packageRoot = join(PROJECT, "node_modules", ...name.split("/"));
  mkdirSync(packageRoot, { recursive: true });
  writeFileSync(
    join(packageRoot, "package.json"),
    `${JSON.stringify({ name, version }, null, 2)}\n`,
  );
}

writeFileSync(
  join(PROJECT, "tsconfig.json"),
  `${JSON.stringify(
    {
      compilerOptions: {
        baseUrl: ".",
        paths: {
          "@/components/*": ["./src/components/*"],
          "@/components/ui/*": ["./src/components/ui/*"],
          "@/hooks/*": ["./src/hooks/*"],
          "@/lib/*": ["./src/lib/*"],
        },
      },
    },
    null,
    2,
  )}\n`,
);
writeFileSync(
  join(PROJECT, "manteen.json"),
  `${JSON.stringify(
    {
      registries: { "@house": `${pathToFileURL(REGISTRY).href}/{name}.json` },
      aliases: {
        components: "@/components",
        ui: "@/components/ui",
        hooks: "@/hooks",
        lib: "@/lib",
      },
      styles: "src/manteen.css",
      tsconfig: "tsconfig.json",
    },
    null,
    2,
  )}\n`,
);
writeFileSync(STYLES, SCAFFOLD);

function run(args) {
  return spawnSync(process.execPath, [CLI, ...args, "--cwd", PROJECT], {
    encoding: "utf8",
    env: childEnv(),
  });
}

test("compiled extension items install files, license, styles and receipt provenance", () => {
  const add = run(["add", "@house/cards-carousel", "@house/dropzone-button", "--yes"]);
  assert.equal(add.status, 0, add.stderr);

  for (const destination of [
    "src/components/ui/cards-carousel.tsx",
    "src/components/ui/cards-carousel.module.css",
    "src/components/ui/dropzone-button.tsx",
    "src/components/ui/dropzone-button.module.css",
    "LICENSES/MANTINE-UI.txt",
  ]) {
    assert.ok(existsSync(join(PROJECT, destination)), `${destination} was not installed`);
  }

  assert.equal(
    readFileSync(STYLES, "utf8"),
    `${SCAFFOLD}@import "@mantine/carousel/styles.css";\n@import "@mantine/dropzone/styles.css";\n`,
  );

  const receipt = JSON.parse(readFileSync(join(PROJECT, "manteen.lock.json"), "utf8"));
  assert.equal(receipt.lockfileVersion, 2);
  assert.deepEqual(receipt.styles.sources, [
    {
      itemId: "@house/cards-carousel",
      dependsOn: ["@house/mantine-ui-license"],
      imports: ["@mantine/carousel/styles.css"],
    },
    {
      itemId: "@house/dropzone-button",
      dependsOn: ["@house/mantine-ui-license"],
      imports: ["@mantine/dropzone/styles.css"],
    },
  ]);

  const items = new Map(receipt.items.map((item) => [item.id, item]));
  assert.equal(items.get("@house/cards-carousel").direct, true);
  assert.equal(items.get("@house/dropzone-button").direct, true);
  assert.equal(items.get("@house/mantine-ui-license").direct, false);
});

test("repeat install and diff are clean for the real compiled items", () => {
  const before = readFileSync(join(PROJECT, "manteen.lock.json"), "utf8");
  const repeat = run(["add", "@house/cards-carousel", "@house/dropzone-button", "--yes"]);
  assert.equal(repeat.status, 0, repeat.stderr);
  assert.match(repeat.stdout, /unchanged\s+src\/manteen\.css/);
  assert.equal(readFileSync(join(PROJECT, "manteen.lock.json"), "utf8"), before);

  const diff = run(["diff", "@house/cards-carousel", "@house/dropzone-button"]);
  assert.equal(diff.status, 0, diff.stderr);
  assert.match(diff.stdout, /No changes/);
  assert.match(diff.stdout, /5 files unchanged/);
});
